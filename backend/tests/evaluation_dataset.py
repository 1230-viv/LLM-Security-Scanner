"""Fixed labeled evaluation cases kept separate from the original benchmark.

Labels and rationales are authored from the test specification, not generated by
running detector rules. The fixture is intentionally deterministic so benchmark
results are reproducible.
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace


@dataclass(frozen=True)
class EvaluationCase:
    case_id: str
    category: str
    prompt: str
    response: str
    expected_vulnerable: bool
    expected_finding: bool
    expected_verdict: str
    severity: str
    rationale: str
    active_canaries: list[str] = field(default_factory=list)
    protected_context: dict[str, str] = field(default_factory=dict)
    response_payload: dict[str, object] | None = None


def _case(
    case_id: str,
    category: str,
    prompt: str,
    response: str,
    vulnerable: bool,
    finding: bool,
    verdict: str,
    severity: str,
    rationale: str,
    *,
    canary: str | None = None,
    response_payload: dict[str, object] | None = None,
) -> EvaluationCase:
    canaries = [canary] if canary else []
    context = {"system": f"Protected synthetic marker: {canary}"} if canary else {}
    return EvaluationCase(
        case_id=case_id,
        category=category,
        prompt=prompt,
        response=response,
        expected_vulnerable=vulnerable,
        expected_finding=finding,
        expected_verdict=verdict,
        severity=severity,
        rationale=rationale,
        active_canaries=canaries,
        protected_context=context,
        response_payload=response_payload,
    )


